// v2.1 meta layer unit tests: challenge seeding, achievements + shop data, skin CSS, policy words.
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const W = p => path.join(__dirname, '..', 'www', p);
const ML = require(W('js/metakit.js'));
const DailyLogic = require(W('js/daily.js'));
const Shop = require(W('js/shopcore.js'));
const ctx = { window: { __bubble: {}, ACH_DEFS: [], Meta: { init() {} } } };
vm.runInNewContext(fs.readFileSync(W('js/meta-config.js'), 'utf8'), ctx);
const C = ctx.window.BUBBLE_META;
assert.ok(C.challenges.length >= 5);
assert.equal(ML.challengeFor('2026-10-14', C.challenges, C.salt).id, ML.challengeFor('2026-10-14', C.challenges, C.salt).id);
const ids = new Set(); for (let d = 1; d <= 30; d++) ids.add(ML.challengeFor('2026-11-' + String(d).padStart(2, '0'), C.challenges, C.salt).id);
assert.ok(ids.size >= 3, 'challenge rotates');
const by = Object.fromEntries(C.challenges.map(c => [c.id, c]));
assert.equal(by.triple.test({ stars: 3 }), true); assert.equal(by.triple.test({ stars: 2 }), false);
assert.equal(by.spare.test({ movesLeft: 5 }), true); assert.equal(by.spare.test({ movesLeft: 4 }), false);
assert.equal(by.blocker.test({ blockers: true }), true);
let r = ML.progressChallenge(null, 'D', by.three, {}); r = ML.progressChallenge(r.prog, 'D', by.three, {}); assert.equal(r.done, false);
r = ML.progressChallenge(r.prog, 'D', by.three, {}); assert.equal(r.done, true);
assert.equal(C.winCoins(), 0, 'level coins stay in Storage.recordWin (no double pay)');
assert.equal(DailyLogic.REWARDS.length, 7);
const actx = { window: {} }; vm.runInNewContext(fs.readFileSync(W('js/ach-defs.js'), 'utf8'), actx);
const defs = actx.window.ACH_DEFS; assert.equal(new Set(defs.map(d => d.id)).size, defs.length);
defs.forEach(d => assert.ok(d.goal > 0 && d.reward > 0 && d.reward <= 250));
assert.ok(defs.find(d => d.id === 'bm_all').goal <= 64);
const css = fs.readFileSync(W('css/meta.css'), 'utf8');
C.shop.forEach(g => { assert.equal(g.items[0].price, 0); g.items.slice(1).forEach(it => assert.ok(css.includes('body.' + g.prefix + it.id), 'css for ' + g.prefix + it.id)); });
css.split('\n').filter(l => /^body\.fin-/.test(l)).forEach(l => assert.ok(!/#[0-9a-f]{3,6}\b/i.test(l), 'finish must keep the bubble hue: ' + l.slice(0, 50)));
const save = { coins: 300, trial: {} }, owned = [];
assert.equal(Shop.buy(save, owned, { id: 'matte', price: 150 }).ok, true); assert.equal(save.coins, 150);
const strip = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/<!--[\s\S]*?-->/g, '').toLowerCase();
const ui = ['index.html', 'js/ui.js', 'js/metakit.js', 'js/meta-config.js', 'js/ach-defs.js', 'js/levels.js'].map(f => strip(fs.readFileSync(W(f), 'utf8'))).join('\n');
['withdraw', 'paypal', 'real money', 'loot box', 'lootbox', 'wager', 'gamble', 'buy coins', 'cow cash', 'chocolate spread', 'color bomb', 'candy', '(stub)', 'ad stub'].forEach(w => assert.ok(!ui.includes(w), 'policy/brand word: ' + w));
assert.ok(!/showRewarded\(|showInterstitial/.test(fs.readFileSync(W('js/metakit.js'), 'utf8')), 'metakit never triggers ads itself');
console.log('ALL META TESTS PASSED');
